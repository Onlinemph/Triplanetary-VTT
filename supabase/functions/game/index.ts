// Dice
// ---------------------------------------------------------------------------

/**
 * A fresh seed, per command, from a source no player can see.
 *
 * "The seed for the next command does not exist until the command arrives."
 * That is the sentence the whole sealed-die design turns on, and this is the
 * function that has to be true for it.
 */
const rollDie = (): number => dieFrom(crypto.getRandomValues(new Uint8Array(4)));

// ---------------------------------------------------------------------------
// create
// ---------------------------------------------------------------------------

/**
 * How many codes to try before giving up.
 *
 * At 31^6 codes a collision is a coincidence, not a load. Six attempts turns a
 * pathologically full namespace into a clean refusal rather than a hang.
 */
const CODE_ATTEMPTS = 6;

/**
 * Sweep away lobbies nobody came back to.
 *
 * `0004_throttle.sql` says this is "called by the referee rather than
 * scheduled, so the migration needs no extension", and `0001_schema.sql` adds
 * `games_status_updated_idx` for exactly this query — but nothing ever called
 * it, so the sweep the design assumed was simply never happening.
 *
 * Create is the right moment. It is the only action that grows the namespace,
 * so tying the sweep to it keeps the table smallest where it matters most: an
 * abandoned lobby that still answers `join` is a live target for code guessing,
 * and every one removed is one fewer.
 *
 * It never fails a create. A player opening a table has no stake in the
 * housekeeping, and a sweep that errored — a lock, a timeout, a permission
 * changed underneath us — must not cost them their game. The failure is logged
 * and swallowed, deliberately, and the next create tries again.
 */
const reapLobbies = async (): Promise<void> => {
  const { error } = await admin.rpc('reap_stale_lobbies');
  if (error) console.error('reaping stale lobbies failed', error.message);
};

const createAction = async (req: CreateRequest, userId: string): Promise<Response> => {
  if (scenarioById(req.scenarioId) === undefined) return refuse('no scenario by that name');

  // A fogged scenario's secrets are a pure function of this number. Escape
  // picks the fugitive with `rollDie({seed: seedOf(opts)})`; Lateral 7 places
  // its dummies from the same draw. The host types the seed into the picker, so
  // honouring it here would hand them the opponent's hidden setup: rebuild the
  // scenario in their own browser, where the whole engine already ships, and
  // read it off. The field survives for open-information play, where the
  // starting position is sent to everybody anyway and a reproducible board is
  // worth having.
  const wantsFog = req.options?.['fogOfWar'] === true;
  const seed = !wantsFog && typeof req.seed === 'number' ? req.seed >>> 0 : rollDie();

  let opening: GameState;
  try {
    // The client chose the options and the fleets, so both are arbitrary JSON
    // until the scenario has looked at them. `buildScenario` is the thing that
    // knows what a hull is called; a refusal here is a bad request, not a bug.
    opening = sealDie(
      buildScenario(req.scenarioId, setupFrom(seed, req.options, req.fleets, req.order)),
    );
  } catch {
    return refuse('that scenario cannot be set up with those options');
  }

  const now = Date.now();
  const seats = openingSeats(opening, req.computerSeats, userId, req.name, now);

  // Fog is read off the built state, never off the request. "Which one is not
  // the client's choice — it is `TableInfo.fog`", and the state is where the
  // scenario recorded its answer.
  const fog = opening.options.fogOfWar;

  for (let attempt = 0; attempt < CODE_ATTEMPTS; attempt += 1) {
    const code = codeFrom(crypto.getRandomValues(new Uint8Array(CODE_LENGTH)));
    const { data, error } = await admin.rpc('create_game', {
      p_code: code,
      p_scenario: req.scenarioId,
      p_fog: fog,
      p_host: userId,
      p_seed: seed,
      p_options: opening.options,
      p_fleets: req.fleets ?? {},
      p_state: opening,
      p_turn: opening.turn,
      p_seats: seats.map(seatToInsert),
    });
    fail('opening the table', error);
    const result = data as { ok: boolean; id?: string; reason?: string } | null;
    if (result === null) throw new Error('create_game answered nothing');
    if (!result.ok) continue; // The only refusal it gives is a taken code.

    const game: StoredGame = {
      id: result.id ?? '',
      code,
      scenarioId: req.scenarioId,
      fog,
      status: 'lobby',
      state: opening,
      commandCount: 0,
      seats,
      hostId: userId,
    };
    // After the table exists, so a slow sweep delays the answer rather than
    // risking it, and awaited rather than left dangling — an Edge Function's
    // worker can be torn down the moment it responds.
    await reapLobbies();
    return answer(seated(game, userId, now));
  }

  return refuse('could not find a free join code; try again');
};


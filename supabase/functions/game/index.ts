const seated = (game: StoredGame, userId: string, now: number): TableResponse => ({
  ok: true,
  table: tableInfo(game, userId, now),
  seat: seatOf(game, userId),
});

/**
 * Write a seat change, and the snapshot a new seat needs to see anything.
 *
 * The views argument is what stops a fog game handing a joining player a blank
 * board until somebody else moves: their `views` row does not exist yet, and
 * `views` is the only thing row level security lets them read.
 */
const writeSeats = async (
  game: StoredGame,
  userId: string,
  next: readonly SeatRow[],
  views: Record<string, GameState>,
): Promise<boolean> => {
  const changed = changedSeats(game.seats, next);
  if (changed.length === 0 && Object.keys(views).length === 0) return true;
  const { data, error } = await admin.rpc('save_seats', {
    p_game: game.id,
    p_user: userId,
    p_seats: changedSeatsToDb(changed),
    p_views: views,
  });
  fail('writing the roster', error);
  return (data as { ok: boolean } | null)?.ok === true;
};

const joinAction = async (req: JoinRequest, userId: string): Promise<Response> => {
  const loaded = await loadGame('code', req.code.toUpperCase());
  const hit = loaded !== null && loaded.game.status !== 'finished';

  // Charge for the guess before answering it. A miss is uniform and says
  // nothing, but a hit announces itself, so a loop over the code space is a
  // search with a payoff — and the only thing that makes it a bad one is the
  // budget. See 0004_throttle.sql. A failure to record is not a reason to
  // refuse a legitimate join: the throttle is a cost, not a gate.
  const { data: allowed, error: throttleError } = await admin.rpc('note_join_attempt', {
    p_user: userId,
    p_hit: hit,
  });
  if (throttleError !== null) console.warn('could not record the attempt', throttleError.message);
  if (allowed === false) return refuse(NO_TABLE);

  if (!hit || loaded === null) return refuse(NO_TABLE);
  const game = loaded.game;

  const now = Date.now();
  const change = takeSeat(game, userId, req.seat, req.name, now);
  if (!change.ok || change.seats === undefined) return refuse(NO_TABLE);

  const next = change.seats;
  const seat = change.seat ?? null;
  const views =
    game.fog && seat !== null && game.status === 'playing'
      ? { [seat]: viewFor({ ...game, seats: next }, seat) }
      : {};

  // A refusal here means somebody took the seat between the read and the write.
  // It is the same outcome as the seat having been taken all along, so it gets
  // the same answer.
  if (!(await writeSeats(game, userId, next, views))) return refuse(NO_TABLE);

  return answer(seated({ ...game, seats: next }, userId, now));
};

const leaveAction = async (game: StoredGame, userId: string): Promise<Response> => {
  const standing = game.seats.find((s) => s.userId === userId);
  const next = leaveSeat(game, userId);
  await writeSeats(game, userId, next, {});

  // Take the board out of the empty chair. The referee keeps a fresh snapshot
  // in `views` for every seat, and a vacated seat is one anybody may sit in —
  // so a row left behind is a fogged board waiting for whoever takes the chair
  // next. It is rewritten on the very next command for whoever is sitting there
  // by then, which is the only person entitled to it.
  if (standing !== undefined && game.fog) {
    const { error } = await admin
      .from('views')
      .delete()
      .eq('game_id', game.id)
      .eq('seat', standing.seat);
    if (error !== null) console.warn('could not clear the vacated view', error.message);
  }
  return answer(seated({ ...game, seats: next }, userId, Date.now()));
};


// ---------------------------------------------------------------------------
// The two clients, and why there are two
// ---------------------------------------------------------------------------

const SUPABASE_URL = Deno.env.get('SUPABASE_URL') ?? '';
const ANON_KEY = Deno.env.get('SUPABASE_ANON_KEY') ?? '';
const SERVICE_KEY = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY') ?? '';

/**
 * The referee's own client, and the only one that touches a table.
 *
 * `service_role` bypasses row level security, which is the entire point: the
 * policies exist to stop *players* reading the board, and the referee is not a
 * player. Nothing built from this client is ever handed a value from a request
 * body without the referee having decided it first.
 */
const admin = createClient(SUPABASE_URL, SERVICE_KEY, {
  auth: { persistSession: false, autoRefreshToken: false },
});

/** `game_secrets` is deliberately absent from `TABLES`: no client names it. */
const SECRETS = 'game_secrets';

// ---------------------------------------------------------------------------
// Answers
// ---------------------------------------------------------------------------

/**
 * Wide open, because the browser bundle is served from wherever the project
 * happens to be hosted and the JWT — not the origin — is what authorises
 * anything. A cross-origin caller with no token gets a 401 and a caller with one
 * is a player, whichever page they came from.
 */
const CORS: Record<string, string> = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type',
  'Access-Control-Allow-Methods': 'POST, OPTIONS',
  'Access-Control-Max-Age': '86400',
};

/**
 * Every answer this function gives is a `PlayResponse`, including the failures.
 *
 * A refusal the referee decided — an illegal move, a taken seat — is a 200,
 * because the request was understood and answered. The 4xx codes are reserved
 * for the envelope: a body that is not a request, a caller with no token, a verb
 * this function does not have. That split is what lets a client read
 * `body.reason` unconditionally instead of guessing whether the body is a
 * response or a gateway's error page.
 */
const answer = (body: PlayResponse, status = 200): Response =>
  new Response(JSON.stringify(body), {
    status,
    headers: { ...CORS, 'content-type': 'application/json; charset=utf-8' },
  });

const refuse = (reason: string, status = 200, seq?: number): Response =>
  answer(seq === undefined ? { ok: false, reason } : { ok: false, reason, seq }, status);

/**
 * One refusal for every way a join can fail.
 *
 * Six characters out of an alphabet of thirty-one is a space worth walking, and
 * a message that distinguishes "no such table" from "that table is full" turns
 * this endpoint into an oracle that says which codes are live. It costs a
 * mistyped code a worse error message, which is the cheaper of the two.
 */
const NO_TABLE = 'no table is waiting on that code';

// ---------------------------------------------------------------------------
// Who is calling
// ---------------------------------------------------------------------------

/**
 * The account behind the request, or null.
 *
 * The header is verified by Supabase rather than parsed here. A JWT this
 * function decoded itself would be a JWT this function could get wrong, and
 * getting it wrong means seating an attacker as somebody else.
 */
const callerOf = async (req: Request): Promise<string | null> => {
  const authorization = req.headers.get('Authorization');
  if (authorization === null || authorization === '') return null;

  const scoped = createClient(SUPABASE_URL, ANON_KEY, {
    global: { headers: { Authorization: authorization } },
    auth: { persistSession: false, autoRefreshToken: false },
  });
  const { data, error } = await scoped.auth.getUser();
  if (error !== null || data.user === null) return null;
  return data.user.id;
};

// ---------------------------------------------------------------------------
// Reading a table
// ---------------------------------------------------------------------------

const GAME_COLUMNS = 'id, code, scenario_id, fog, status, turn, command_count, host_id';
const SEAT_COLUMNS = 'seat, ordinal, faction, name, kind, user_id, last_seen';

const fail = (what: string, error: { message: string } | null): void => {
  if (error !== null) throw new Error(`${what}: ${error.message}`);
};

/**
 * Load a whole table: the public row, the secret board, the roster.
 *
 * The order of the two reads is load-bearing and not an accident of style.
 * `command_count` comes from `games` and the board comes from `game_secrets`,
 * and the pair is handed to `apply_command` as "this board is the board at log
 * length N". Read the board first and a command landing in the gap makes N one
 * too *large* for the board we hold — and `apply_command`'s staleness check,
 * which compares N against the log, would wave it through and write a board a
 * move behind its own log. Read `games` first and the same race makes N one too
 * small, which that check catches and refuses. Same window, opposite outcome.
 */
interface Loaded {
  readonly game: StoredGame;
  /** The seed and setup choices, kept so an open sync can rebuild `initial`. */
  readonly setup: SecretRow;
}

const loadGame = async (by: 'id' | 'code', value: string): Promise<Loaded | null> => {
  const found = await admin.from(TABLES.games).select(GAME_COLUMNS).eq(by, value).maybeSingle();
  fail('reading the table', found.error);
  if (found.data === null) return null;
  const row = found.data as unknown as GameRow;

  const [secret, seats] = await Promise.all([
    admin.from(SECRETS).select('seed, options, fleets, state').eq('game_id', row.id).maybeSingle(),
    admin.from(TABLES.seats).select(SEAT_COLUMNS).eq('game_id', row.id),
  ]);
  fail('reading the board', secret.error);
  fail('reading the roster', seats.error);
  if (secret.data === null) return null;

  const setup = secret.data as unknown as SecretRow;
  return { game: storedGame(row, setup, (seats.data ?? []) as unknown as SeatDbRow[]), setup };
};

/**
 * The command log from `since` onwards, in pages.
 *
 * `max_rows = 200` in config.toml caps every PostgREST response, and it caps
 * silently — a long game read in one request would come back truncated and
 * replay to the wrong board with nothing anywhere saying so. So the log is read
 * until a short page arrives.
 */
const LOG_PAGE = 200;

const readLog = async (gameId: string, since: number): Promise<LoggedCommand[]> => {
  const out: LoggedCommand[] = [];
  for (;;) {
    // The cursor is the last index actually read, not `since` plus a count. The
    // log is gapless so the two agree, and taking it from the data means this
    // loop cannot spin if that ever stops being true.
    const from = out[out.length - 1]?.idx ?? since;
    const page = await admin
      .from(TABLES.commands)
      .select('idx, cmd, die')
      .eq('game_id', gameId)
      .gt('idx', from)
      .order('idx', { ascending: true })
      .range(0, LOG_PAGE - 1);
    fail('reading the log', page.error);
    const rows = (page.data ?? []) as unknown as { idx: number; cmd: Command; die: number }[];
    for (const row of rows) out.push(loggedFromDb(row));
    if (rows.length < LOG_PAGE) return out;
  }
};


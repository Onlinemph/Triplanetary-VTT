/**
 * The referee, on the wire.
 *
 * One function, one POST, one `action` per `PlayRequest`. Everything a table
 * does online goes through here, because this is the only participant that holds
 * the service role — the only one that may write the command log, read the seed,
 * or see the whole board. Every other participant is a browser with a seat and a
 * JWT, and 0002_policies.sql decides what that entitles it to read.
 *
 * Three rules run through the whole file.
 *
 * **Identity comes off the JWT and nowhere else.** The caller's account is read
 * by handing their `Authorization` header to a client built with the *anon* key
 * and asking Supabase who it belongs to. Nothing in the request body is ever
 * consulted for who somebody is; `by` inside a command is checked against the
 * seat that account holds, which is the one thing a relay cannot do and the
 * reason the field means anything.
 *
 * **The referee decides nothing.** `src/net/supabase/referee.ts` judges orders,
 * seats players, rolls the dice and redacts the board. This file reads rows,
 * calls one of those, and writes rows. When the two disagree the referee is
 * right, because the referee is the part with tests.
 *
 * **A half-written command is a corrupted game.** Accepting an order touches
 * four tables and PostgREST gives one transaction per request, so the four
 * writes are handed to `apply_command` in 0003_apply.sql and committed together.
 * The same function serialises concurrent orders and refuses the stale one; see
 * `commandAction` below and the header of that migration.
 *
 * ## The die
 *
 * Every seed this function rolls with comes from `crypto.getRandomValues` and
 * goes into the log beside the command it was used on. The stored board's own
 * generator is sealed to zero and never rolled with, so a leak of the state is
 * not a leak of the dice, and a replay of the log is still exact.
 *
 * ## The engine
 *
 * Deno cannot read this codebase's TypeScript: the imports carry a `.js`
 * extension that means `.ts` and reach through `@engine/`-style aliases. So the
 * rules arrive pre-bundled at `../_shared/engine.js`, which is generated by
 * `scripts/build-functions.mjs` and not committed. Run `npm run functions:build`
 * before deploying; `npm run functions:deploy` does it for you.
 */


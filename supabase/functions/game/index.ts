/**
 * Catch up.
 *
 * A seated player gets what their seat is entitled to. A caller with no seat is
 * a spectator, and gets what `viewFor(game, null)` gives — everything in an open
 * game, only what is public in a fog one. That is a deliberate widening of the
 * database's own rule, which grants nothing for merely holding an id: a
 * spectator cannot read any of these tables directly and has no `views` row to
 * subscribe to, so the whole of their access is this call, through the referee,
 * filtered by the referee.
 */
const syncAction = async (req: SyncRequest, userId: string): Promise<Response> => {
  const loaded = await loadGame('id', req.gameId);
  if (loaded === null) return refuse('no such table');
  const { game, setup } = loaded;

  const seat = seatOf(game, userId);
  const since = typeof req.since === 'number' && req.since > 0 ? Math.floor(req.since) : 0;

  let open: { initial: GameState | null; log: readonly LoggedCommand[] } | null = null;
  if (!game.fog) {
    try {
      open = {
        // Only on a full sync. A tail is meant to be applied to the board the
        // client already holds, and sending the starting position beside it
        // invites exactly the mistake it caused: replay three commands onto
        // turn one and call it caught up.
        initial:
          since === 0
            ? buildScenario(
                game.scenarioId,
                // A campaign order is not stored on its own row: the opening
                // state embedded it in `scenarioData` at create, nothing in
                // play ever rewrites it, and the stored board is the same
                // state a few commands later — so it is read back from there.
                setupFrom(
                  setup.seed,
                  setup.options,
                  setup.fleets,
                  setup.state.scenarioData['order'],
                ),
              )
            : null,
        log: await readLog(game.id, since),
      };
    } catch {
      // The scenario the game was built from is no longer in this build. The
      // log cannot be replayed onto a starting position that cannot be
      // rebuilt, so fall back to shipping the board itself — worse for audit,
      // but a game somebody can still finish.
      open = null;
    }
  }

  // Presence, but only when it is actually stale.
  //
  // Writing it unconditionally is a loop with no exit: `touch_seat` sets
  // `last_seen = now()`, which is a genuine row change, which `seats` streams
  // to every client at the table, each of which re-syncs, each of which writes
  // its presence again. Half of `PRESENCE_MS` keeps the dot accurate and turns
  // the storm into one write per seat per twenty-odd seconds.
  const mine = seat === null ? undefined : game.seats.find((s) => s.seat === seat);
  const stale =
    mine !== undefined && (mine.lastSeen === null || Date.now() - mine.lastSeen > PRESENCE_MS / 2);
  if (stale) {
    // A failed presence write must not lose the sync: the caller is asking to
    // catch up, and a dimmed dot beats an error page.
    const { error } = await admin.rpc('touch_seat', { p_game: game.id, p_seat: seat });
    if (error !== null) console.warn('could not record presence', error.message);
  }

  return answer(syncResponse(game, seat, userId, Date.now(), open));
};


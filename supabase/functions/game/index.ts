const dispatch = async (req: PlayRequest, userId: string): Promise<Response> => {
  switch (req.action) {
    case 'create':
      return createAction(req, userId);
    case 'join':
      return joinAction(req, userId);
    case 'sync':
      return syncAction(req, userId);
    case 'command':
      return commandAction(req.gameId, req.cmd, userId, req.seq);
    case 'leave':
    case 'start': {
      const loaded = await loadGame('id', req.gameId);
      if (loaded === null) return refuse('no such table');
      return req.action === 'leave'
        ? leaveAction(loaded.game, userId)
        : startAction(loaded.game, userId);
    }
  }
};

Deno.serve(async (request: Request): Promise<Response> => {
  if (request.method === 'OPTIONS') return new Response(null, { status: 204, headers: CORS });
  if (request.method !== 'POST') {
    return refuse('this referee only answers POST', 405);
  }

  let body: unknown;
  try {
    body = await request.json();
  } catch {
    return refuse('that request was not JSON', 400);
  }

  // Version before shape, because an old client in the wild is by far the most
  // likely reason a well-formed request fails to parse, and "malformed" is a
  // uselessly wrong thing to tell it.
  const version = (body as { v?: unknown } | null)?.v;
  if (version !== SUPABASE_PROTOCOL_VERSION) {
    return refuse(`this referee speaks protocol ${String(SUPABASE_PROTOCOL_VERSION)}`, 400);
  }

  const parsed = parsePlayRequest(body);
  if (parsed === null) return refuse('that is not a request this referee understands', 400);

  const userId = await callerOf(request);
  if (userId === null) return refuse('sign in before sitting down', 401);

  try {
    return await dispatch(parsed, userId);
  } catch (thrown) {
    // The message may name a table, a column or a constraint. That belongs in
    // the logs, where the person who can fix it is looking, and nowhere near a
    // response body.
    console.error('game function failed', thrown);
    return refuse('the referee could not answer that just now', 500);
  }
});

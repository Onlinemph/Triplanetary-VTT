// start
// ---------------------------------------------------------------------------

/**
 * Close the lobby.
 *
 * Host only, and the host is `games.host_id` rather than "whoever is in seat
 * one" — the two come apart the moment the host hands their seat to somebody
 * else, and the person who opened the table is the one who should decide when it
 * begins.
 *
 * `playComputerSeats` runs immediately, so a solo table is already waiting on
 * the human by the time this returns rather than after some later poke.
 */
const startAction = async (game: StoredGame, userId: string): Promise<Response> => {
  if (game.hostId !== userId) return refuse('only the host may start this game');
  const notReady = readyToStart(game);
  if (notReady !== null) return refuse(notReady);

  const playing: StoredGame = { ...game, status: 'playing' };
  const out = playComputerSeats(playing, rollDie);
  const final = out.game;

  const written = await commit(final, game.commandCount, out.logged, seatOf(final, userId));
  if (!written.ok) return refuse('somebody else started this game first');
  return answer(seated(final, userId, Date.now()));
};

// ---------------------------------------------------------------------------
// command
// ---------------------------------------------------------------------------

/**
 * The four writes, as one.
 *
 * `expect` is the log length the new board was computed from. `apply_command`
 * takes the game's row lock, checks the log is still that long, and either
 * commits every row or commits none of them.
 *
 * The views are recomputed from the final board rather than taken from
 * `playComputerSeats`, which returns none when the computer had nothing to say —
 * and a fog game whose seats do not all get a fresh snapshot after every command
 * has some of them looking at a stale board.
 */
const commit = async (
  game: StoredGame,
  expect: number,
  logged: readonly LoggedCommand[],
  seat: string | null,
): Promise<{ ok: boolean }> => {
  const { data, error } = await admin.rpc('apply_command', {
    p_game: game.id,
    p_expect_count: expect,
    p_state: game.state,
    p_status: game.status,
    p_turn: game.state.turn,
    p_commands: logged.map(logRow),
    p_views: game.fog ? viewsForAll(game) : {},
    p_seat: seat,
  });
  fail('recording the command', error);
  const result = data as { ok: boolean; reason?: string } | null;
  return { ok: result?.ok === true };
};

/**
 * How many times to re-judge an order that lost a race.
 *
 * Retrying is safe because nothing is retried: the order is judged again from
 * the board as it now stands, so an order the intervening command made illegal
 * is refused on the rules rather than replayed. What is not safe is retrying
 * forever, which turns a busy table into a livelock.
 */
const COMMAND_ATTEMPTS = 3;

const commandAction = async (
  gameId: string,
  cmd: Command,
  userId: string,
  seq: number | undefined,
): Promise<Response> => {
  for (let attempt = 0; attempt < COMMAND_ATTEMPTS; attempt += 1) {
    const loaded = await loadGame('id', gameId);
    if (loaded === null) return refuse('no such table', 200, seq);
    const game = loaded.game;

    const seat = seatOf(game, userId);
    const verdict = judge(game, seat, cmd, rollDie());
    if (!verdict.ok) return refuse(verdict.reason, 200, seq);

    // The computer answers inside the same move. A human's order and every
    // order the referee's own seats gave in reply are one indivisible thing:
    // committing the first without the second would leave a board waiting on a
    // player that no longer has to act.
    const after = playComputerSeats(verdict.game, rollDie);
    const final = after.game;
    const logged = [verdict.logged, ...after.logged];

    const written = await commit(final, game.commandCount, logged, seat);
    if (written.ok) return answer({ ok: true, index: final.commandCount, seq });
  }

  return refuse('the table is busy; try that again', 200, seq);
};


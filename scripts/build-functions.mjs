/**
 * Make the engine importable by Deno.
 *
 * The Edge Function is the referee, and a referee that cannot call
 * `applyCommand` is worth nothing — so the rules have to reach Deno intact. They
 * cannot get there as source. This codebase writes relative imports with a
 * `.js` extension that points at a `.ts` file, and reaches across itself with
 * `@engine/`-style aliases; both are conventions TypeScript understands and
 * Deno's resolver does not. Nor can the function reach up out of
 * `supabase/functions/` at deploy time: the CLI uploads that directory and
 * nothing above it.
 *
 * So the rules are bundled. One file, no imports left in it, written into
 * `supabase/functions/_shared/engine.js` where the function can see it. esbuild
 * does the resolving — it reads the same `tsconfig.json` the browser build
 * reads, so the aliases and the `.js`-means-`.ts` convention are honoured by the
 * project's own configuration rather than by a second copy of it here.
 *
 * ## The surface is written out by hand, and that is the point
 *
 * `ENTRY` below re-exports a named list rather than `export *`. The bundle is a
 * contract between two programs that are deployed separately, and a contract
 * that says "everything" cannot be read. It also keeps the bundle honest about
 * its size: nothing arrives in Deno that no function call asked for.
 *
 * ## Types
 *
 * esbuild erases types and cannot emit declarations. Rather than hand-write a
 * `.d.ts` — which would be a second copy of the contract, free to drift from the
 * first — the build writes one that re-exports from the original sources.
 * TypeScript resolves `./x.js` to `./x.ts` and follows the path aliases, so an
 * editor opened on the function sees the real types, always current. Deno never
 * reads it: it only consults a sibling declaration when a `@deno-types` comment
 * points at one, and nothing here does.
 *
 * That file is committed, unlike the bundle beside it. It carries no compiled
 * code, and `npm run typecheck` needs it to resolve `../_shared/engine.js` —
 * which means a fresh clone that has never run this script must still have it,
 * and a fresh clone is exactly what CI is. `--check` fails if the committed copy
 * is not what this script would write, so the two cannot drift apart.
 *
 * ## Verification
 *
 * A bundle that builds and then throws on import is worse than no bundle,
 * because the failure surfaces in production. So the build imports its own
 * output, builds a scenario and judges a command through the referee, and fails
 * the build if the game that comes back is not a real one. Pass `--check` to run
 * only that, against the bundle already on disk.
 */

import { build } from 'esbuild';
import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const SHARED = join(ROOT, 'supabase', 'functions', '_shared');
const OUT = join(SHARED, 'engine.js');
const TYPES = join(SHARED, 'engine.d.ts');

/**
 * The modules the bundle republishes, and the names it takes from each.
 *
 * Keep this list minimal. Everything here is code shipped to a Deno worker on
 * every cold start, and everything absent is code the function has decided it
 * does not need.
 */
const SURFACE = [
  {
    from: 'src/net/supabase/protocol.js',
    values: ['SUPABASE_PROTOCOL_VERSION', 'TABLES', 'parsePlayRequest'],
  },
  {
    from: 'src/net/supabase/referee.js',
    values: [
      'CODE_LENGTH',
      'codeFrom',
      'judge',
      'leaveSeat',
      'playComputerSeats',
      'seatOf',
      'tableInfo',
      'takeSeat',
      'viewFor',
      'viewsForAll',
    ],
  },
  { from: 'src/net/redact.js', values: ['sealDie'] },
  { from: 'src/scenarios/index.js', values: ['buildScenario', 'scenarioById'] },
  // The map every rules call defaults to, and — through the declaration file
  // below — where `GameState`, `Command` and `PlayerId` come from. The engine's
  // modules are already in the bundle by way of the referee, so this line adds
  // a name rather than a payload.
  { from: 'src/engine/index.js', values: ['DEFAULT_MAP'] },
];

const ENTRY = SURFACE.map((m) => `export { ${m.values.join(', ')} } from './${m.from}';`).join(
  '\n',
);

/**
 * The declaration file, pointed at the sources rather than at the bundle.
 *
 * `export *` is right here and wrong in `ENTRY`: types cost nothing at runtime,
 * and the narrower the re-export list the more often this file would have to be
 * edited in step with a function that only wanted one more interface.
 */
const declarations = () => {
  const to = relative(SHARED, ROOT).split('\\').join('/');
  const lines = SURFACE.map((m) => `export * from '${to}/${m.from}';`);
  return [
    '// Generated by scripts/build-functions.mjs. Do not edit.',
    '//',
    '// The types behind supabase/functions/_shared/engine.js, taken from the',
    '// sources it was bundled from so the two cannot drift apart.',
    '',
    ...lines,
    '',
  ].join('\n');
};

const bundle = async () => {
  await mkdir(SHARED, { recursive: true });
  const result = await build({
    stdin: { contents: ENTRY, resolveDir: ROOT, sourcefile: 'engine.entry.ts', loader: 'ts' },
    bundle: true,
    format: 'esm',
    // Neutral, not "node" and not "browser": the bundle must not acquire a
    // shim for either. Anything in the engine that reached for a platform
    // global would fail here rather than at three in the morning on Deno.
    platform: 'neutral',
    target: 'es2022',
    // The one line that makes `@engine/...` and `./x.js` resolve. It is the
    // project's own tsconfig, so the bundle cannot disagree with the browser
    // build about what a specifier means.
    tsconfig: join(ROOT, 'tsconfig.json'),
    // Readable, because this is the code that decides games and somebody will
    // one day have to read a stack trace through it. The engine is small.
    minify: false,
    legalComments: 'none',
    outfile: OUT,
    metafile: true,
    logLevel: 'warning',
  });

  const imports = Object.values(result.metafile.outputs)[0]?.imports ?? [];
  if (imports.length > 0) {
    throw new Error(
      `the bundle still imports ${imports.map((i) => i.path).join(', ')} — it must be self-contained`,
    );
  }

  await writeFile(TYPES, declarations(), 'utf8');
  return {
    bytes: (await stat(OUT)).size,
    modules: Object.keys(result.metafile.inputs).length,
  };
};

/**
 * Prove the bundle runs.
 *
 * Not a type check and not a unit test — those live upstream, against the
 * sources. The single question here is whether the *bundling* preserved a
 * working engine, and the way to answer it is to play. `src/scenarios/index.ts`
 * registers the victory checker and the turn hooks as a side effect of being
 * loaded, so a tree shake that dropped them would leave a bundle that imports
 * cleanly and then judges wrongly: judging a real command is what catches it.
 */
const smokeTest = async () => {
  const engine = await import(pathToFileURL(OUT).href);
  const state = engine.sealDie(engine.buildScenario('flight-school', { seed: 20250824 }));
  const seat = state.playerOrder[0];
  if (!seat || Object.keys(state.ships).length === 0) {
    throw new Error('the bundle built a scenario with nobody in it');
  }

  const game = {
    id: '00000000-0000-4000-8000-000000000000',
    code: 'ABCDEF',
    scenarioId: state.scenarioId,
    fog: state.options.fogOfWar,
    status: 'playing',
    state,
    commandCount: 0,
    hostId: '00000000-0000-4000-8000-000000000001',
    seats: [
      {
        seat,
        ordinal: 0,
        faction: state.players[seat].faction,
        name: state.players[seat].name,
        kind: 'human',
        userId: '00000000-0000-4000-8000-000000000001',
        lastSeen: null,
      },
    ],
  };

  const judged = engine.judge(game, seat, { type: 'endPhase', by: seat }, 0x5eed5eed);
  if (!judged.ok) throw new Error(`the referee refused a legal order: ${judged.reason}`);
  if (judged.game.commandCount !== 1) throw new Error('the referee did not extend the log');
  if (judged.game.state.rng.seed !== 0) throw new Error('the referee handed back an unsealed die');
  if (judged.logged.die !== 0x5eed5eed) throw new Error('the log did not record the die rolled');
  if (judged.game.state.phase === state.phase) throw new Error('the phase did not advance');

  // Spectators cannot act, and that check has to survive bundling too — it is
  // the one gate a relay cannot do and the reason `by` means anything.
  const refused = engine.judge(game, null, { type: 'endPhase', by: seat }, 1);
  if (refused.ok) throw new Error('the bundle let a spectator issue an order');

  return `${state.scenarioId}: ${state.phase} -> ${judged.game.state.phase}`;
};

/**
 * Is the committed declaration still the one this script would write?
 *
 * It is the only generated file here that lives in git, because the typecheck
 * needs it on a machine that has never run this script. Committed and generated
 * is a combination that rots quietly, so the two are compared rather than
 * trusted: add a module to `SURFACE` and forget to rebuild, and this says so.
 */
const checkDeclarations = async () => {
  const want = declarations();
  const have = await readFile(TYPES, 'utf8').catch(() => null);
  if (have === want) return;
  throw new Error(
    have === null
      ? `${relative(ROOT, TYPES)} is missing — run \`npm run functions:build\``
      : `${relative(ROOT, TYPES)} is out of date with SURFACE — run \`npm run functions:build\``,
  );
};

const main = async () => {
  const checkOnly = process.argv.includes('--check');
  if (!checkOnly) {
    const { bytes, modules } = await bundle();
    process.stdout.write(
      `engine.js  ${(bytes / 1024).toFixed(1)} kB from ${String(modules)} modules\n`,
    );
  }
  await checkDeclarations();
  process.stdout.write(`smoke test ok  ${await smokeTest()}\n`);
};

await main();
